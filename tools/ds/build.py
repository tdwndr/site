# ---------- colour maths ----------
def rgb(h): h = h.lstrip("#"); return [int(h[i:i + 2], 16) for i in (0, 2, 4)]
def hexs(c): return "#" + "".join("%02X" % max(0, min(255, round(v))) for v in c)
def mix(a, b, p): return hexs([x * p + y * (1 - p) for x, y in zip(rgb(a), rgb(b))])
def lum(h):
    def f(v): v /= 255; return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(h); return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
def ratio(a, b):
    x, y = sorted([lum(a), lum(b)], reverse=True); return (x + 0.05) / (y + 0.05)
def derived(c):
    return {"muted": mix(c["ink"], c["paper"], .72), "rule": mix(c["ink"], c["paper"], .14), "rule-strong": mix(c["ink"], c["paper"], .38), "wash": mix(c["accent"], c["paper"], .09)}

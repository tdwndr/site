def slugify(s): return re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", s).lower()).strip("-")
def dedent_code(s): return html.escape(textwrap.dedent(s).strip("\n"))

def process_demo(m):
    attrs, inner = m.group(1), m.group(2)
    ctx = re.search(r'context="(\w+)"', attrs); title = re.search(r'title="([^"]+)"', attrs)
    nocode = "nocode" in attrs; wide = "wide" in attrs
    ctxa = f' data-context="{ctx.group(1)}"' if ctx else ""
    code = "" if nocode else f'<details class="demo__code"><summary>HTML</summary><pre class="code"><code>{dedent_code(inner)}</code></pre></details>'
    cap = f'<figcaption class="demo__title eyebrow">{title.group(1)}</figcaption>' if title else ""
    return f'<figure class="demo{" demo--wide" if wide else ""}">{cap}<div class="demo__stage"{ctxa}>{textwrap.dedent(inner).strip()}</div>{code}</figure>'

AI_ORDER = []
def md_inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', t)
    return t
def md(src):
    out, lst, para, quote, i = [], None, [], [], 0
    L = src.splitlines()
    def flush():
        nonlocal lst, para, quote
        if para: out.append("<p>" + md_inline(" ".join(para)) + "</p>"); para = []
        if quote: out.append("<blockquote>" + "".join("<p>" + md_inline(q) + "</p>" for q in quote if q) + "</blockquote>"); quote = []
        if lst: out.append(f"</{lst}>"); lst = None
    while i < len(L):
        ln = L[i]
        if ln.startswith("```"):
            flush(); code = []; i += 1
            while i < len(L) and not L[i].startswith("```"): code.append(L[i]); i += 1
            out.append('<pre class="code"><code>' + html.escape("\n".join(code)) + "</code></pre>"); i += 1; continue
        m = re.match(r"(#{1,4}) (.*)", ln)
        if m: flush(); n = len(m.group(1)) + 1; out.append(f"<h{n}>{md_inline(m.group(2))}</h{n}>"); i += 1; continue
        m = re.match(r"\s*(?:[-*]|(\d+)\.) (.*)", ln)
        if m:
            kind = "ol" if m.group(1) else "ul"
            if para or quote: 
                p0 = lst; flush()
            if lst != kind:
                if lst: out.append(f"</{lst}>")
                out.append(f"<{kind}>"); lst = kind
            out.append("<li>" + md_inline(m.group(2)) + "</li>"); i += 1; continue
        if ln.startswith(">"): 
            if lst or para: flush()
            quote.append(ln.lstrip("> ").rstrip()); i += 1; continue
        if not ln.strip(): flush(); i += 1; continue
        if lst: flush()
        para.append(ln.strip()); i += 1
    flush()
    return "\n".join(out)

def md_raw(src):
    out = []
    fence = False
    for ln in src.rstrip().splitlines():
        e = html.escape(ln)
        if ln.startswith("```"):
            fence = not fence; out.append(f'<span class="m-fence">{e}</span>'); continue
        if fence: out.append(f'<span class="m-code">{e}</span>'); continue
        if re.match(r"#{1,4} ", ln): out.append(f'<span class="m-h">{e}</span>'); continue
        e = re.sub(r"\*\*(.+?)\*\*", r'<span class="m-b">**\1**</span>', e)
        e = re.sub(r"`([^`]+)`", r'<span class="m-c">`\1`</span>', e)
        e = re.sub(r"^(\s*)([-*]|\d+\.) ", r'\1<span class="m-li">\2</span> ', e)
        e = re.sub(r"^&gt; ", '<span class="m-q">&gt;</span> ', e)
        out.append(e)
    return "\n".join(out)


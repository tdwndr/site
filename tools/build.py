#!/usr/bin/env python3
"""Regenerate the /tools list (and the rules that hide unfinished tools).

Run:  python3 tools/build.py          rewrite the list, print what it found
      python3 tools/build.py --check  change nothing; exit 1 if anything is stale
      python3 tools/build.py --touch  also bump "updated" to today

A folder is listed when it contains an index.html. Marker files change that:
  .unlinked  listed by name, not clickable, and NOT served (404) once deployed
  .unlisted  not shown at all, and NOT served (404) once deployed
Folders starting with `_` are ignored by the list and NOT served either.
Put one short line in `description.txt` inside a folder to show it beside the name.

"Updated" is stored in the list's marker comment and only moves when the list
itself changes (a tool added, removed, renamed, relinked or re-described).

Hiding works through /_redirects (Netlify), written between `# tools:start` and
`# tools:end`. In live tools, helper files that only matter to the repo (build.py,
template.html, README.md, description.txt, marker files and any src/ folder) are
also blocked, so they stay out of the public site.

The same run keeps the tools entries in /sitemap.xml and the Tools section of
/llms.txt up to date, each between the same start and end markers. A local `python3 -m http.server` ignores it, so unfinished tools
still open on localhost; they are only blocked on the live site.
"""
import re, sys, html, datetime
from pathlib import Path

root = Path(__file__).parent
page = root / "index.html"
redirects = root.parent / "_redirects"
sitemap = root.parent / "sitemap.xml"
llms = root.parent / "llms.txt"
SITE = "https://tedw.co.uk"
PRIVATE_FILES = ["build.py", "template.html", "README.md", "description.txt", ".unlinked", ".unlisted"]
PRIVATE_DIRS = ["src"]
check, touch = "--check" in sys.argv, "--touch" in sys.argv
today = datetime.date.today().isoformat()


def scan():
    listed, hidden = [], []
    for d in sorted(root.iterdir(), key=lambda p: p.name.lower()):
        if not d.is_dir() or d.name.startswith("."):
            continue
        if d.name.startswith("_") or (d / ".unlisted").exists():
            hidden.append(d.name)
            continue
        if not (d / "index.html").exists():
            continue
        unlinked = (d / ".unlinked").exists()
        desc = d / "description.txt"
        text = (desc.read_text().strip().splitlines() or [""])[0] if desc.exists() else ""
        listed.append((d.name, unlinked, text))
        if unlinked:
            hidden.append(d.name)
    return listed, hidden


def render(listed, date):
    def row(n, off, desc):
        n = html.escape(n)
        slash = '<span class="slash" aria-hidden="true">/</span>'
        name = (f'<span class="name">{slash}{n}</span>' if off
                else f'<a class="name" href="/tools/{n}/">{slash}{n}</a>')
        d = f'<span class="desc">{html.escape(desc)}</span>' if desc else ""
        cls = ' class="unlinked"' if off else ""
        return f"      <li{cls}>{name}{d}</li>"

    items = "\n".join(row(*t) for t in listed) or '      <li class="empty">Nothing here yet.</li>'
    nice = datetime.date.fromisoformat(date).strftime("%-d %b %Y")
    return (
        f"<!-- tools:start updated={date} (generated by tools/build.py: do not edit by hand) -->\n"
        '    <p class="prompt"><span class="path" aria-hidden="true">/tools/<span class="typed" id="typed"></span>'
        '<span class="caret"></span></span>'
        f'<span class="updated">updated <time datetime="{date}">{nice}</time></span></p>\n'
        f'    <ul class="tools">\n{items}\n    </ul>\n'
        "    <!-- tools:end -->"
    )


def redirect_block(listed, hidden):
    lines = ["# tools:start (generated by tools/build.py: do not edit by hand)",
             "/tools/build.py /404.html 404!"]
    for n in hidden:
        lines += [f"/tools/{n} /404.html 404!", f"/tools/{n}/* /404.html 404!"]
    for n, off, _ in listed:          # live tools: block repo-only helper files
        if n in hidden:
            continue
        lines += [f"/tools/{n}/{f} /404.html 404!" for f in PRIVATE_FILES if (root / n / f).exists()]
        lines += [f"/tools/{n}/{d}/* /404.html 404!" for d in PRIVATE_DIRS if (root / n / d).is_dir()]
    lines.append("# tools:end")
    return "\n".join(lines)


def sitemap_block(listed, date):
    urls = [f"  <url>\n    <loc>{SITE}/tools/</loc>\n    <lastmod>{date}</lastmod>\n  </url>"]
    urls += [f"  <url>\n    <loc>{SITE}/tools/{html.escape(n)}/</loc>\n  </url>" for n, off, _ in listed if not off]
    return ("<!-- tools:start (generated by tools/build.py: do not edit by hand) -->\n"
            + "\n".join(urls) + "\n  <!-- tools:end -->")


def llms_block(listed):
    live = [(n, d) for n, off, d in listed if not off]
    items = "\n".join(f"- [/{n}]({SITE}/tools/{n}/)" + (f": {d}" if d else "") for n, d in live) or "- Nothing here yet."
    return ("<!-- tools:start (generated by tools/build.py: do not edit by hand) -->\n"
            "## Tools\n\n"
            f"Small tools and experiments Ted has made, listed at {SITE}/tools/.\n\n"
            f"{items}\n"
            "<!-- tools:end -->")


def replace_block(path, block, pat):
    cur = path.read_text() if path.exists() else ""
    if not pat.search(cur):
        sys.exit(f"{path.name}: tools:start / tools:end markers not found")
    return cur, pat.sub(lambda _: block, cur)


listed, hidden = scan()
src = page.read_text()
m = re.search(r"<!-- tools:start updated=(\d{4}-\d{2}-\d{2})", src)
stored = m.group(1) if m else today
pat = re.compile(r"<!-- tools:start.*?<!-- tools:end -->", re.S)

new_page = pat.sub(lambda _: render(listed, stored), src)
date = stored
if not check and (new_page != src or touch):
    date = today                      # the list changed: bump "updated"
    new_page = pat.sub(lambda _: render(listed, date), src)

cur = redirects.read_text() if redirects.exists() else ""
block = redirect_block(listed, hidden)
rpat = re.compile(r"# tools:start.*?# tools:end", re.S)
new_red = rpat.sub(lambda _: block, cur) if rpat.search(cur) else (cur.rstrip("\n") + "\n\n" if cur.strip() else "") + block + "\n"

print("Listed:", ", ".join(n + (" (unlinked)" if off else "") for n, off, _ in listed) or "(none)")
print("Not served:", ", ".join(hidden) or "(none)")
mpat = re.compile(r"<!-- tools:start.*?<!-- tools:end -->", re.S)
cur_map, new_map = replace_block(sitemap, sitemap_block(listed, date), mpat)
cur_llms, new_llms = replace_block(llms, llms_block(listed), mpat)

if check:
    stale = [f for f, a, b in (("tools/index.html", src, new_page), ("_redirects", cur, new_red),
                               ("sitemap.xml", cur_map, new_map), ("llms.txt", cur_llms, new_llms)) if a != b]
    if stale:
        print("Out of date:", ", ".join(stale), "-> run: python3 tools/build.py")
        sys.exit(1)
    print("Up to date.")
else:
    page.write_text(new_page)
    redirects.write_text(new_red)
    sitemap.write_text(new_map)
    llms.write_text(new_llms)
    print("Updated:", date)
